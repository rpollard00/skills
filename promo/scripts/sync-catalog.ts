import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const PROMO = path.resolve(import.meta.dirname, "..");
const REPO = path.resolve(PROMO, "..");
const SKILLS_DIR = path.join(REPO, "skills");
const PLAYBOOKS_DIR = path.join(SKILLS_DIR, "mako", "playbooks");
const README = path.join(REPO, "README.md");
const GENERATED = path.join(PROMO, "src", "catalog.generated.ts");

const NUMBER_WORDS = [
  "zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten",
  "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen",
  "nineteen", "twenty",
];

const README_COUNTS = {
  skills: /(\S+) skills:/,
  engineering: /(\S+) engineering skills/,
  principles: /(\S+) independent engineering principles/,
  craft: /(\S+) design, version-control, and writing skills/,
  playbooks: /(\S+) task playbooks/,
} as const;

type CountName = keyof typeof README_COUNTS;
const COUNT_NAMES: readonly CountName[] = ["skills", "engineering", "principles", "craft", "playbooks"];

const readSkillNames = (): string[] =>
  readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(path.join(SKILLS_DIR, entry.name, "SKILL.md")))
    .map((entry) => entry.name)
    .sort();

const readPlaybookNames = (): string[] =>
  readdirSync(PLAYBOOKS_DIR)
    .filter((file) => file.endsWith(".md"))
    .map((file) => file.slice(0, -".md".length))
    .sort();

const constArray = (name: string, values: readonly string[]): string =>
  `export const ${name} = [\n${values.map((value) => `  ${JSON.stringify(value)},\n`).join("")}] as const;\n`;

const render = (skills: readonly string[], playbooks: readonly string[]): string =>
  [
    "// GENERATED by scripts/sync-catalog.ts from ../skills. Do not edit. Run: npm run sync\n",
    constArray("SKILLS", skills),
    constArray("PLAYBOOKS", playbooks),
  ].join("\n");

const parseCount = (word: string): number | null => {
  if (/^\d+$/.test(word)) return Number(word);
  const index = NUMBER_WORDS.indexOf(word.toLowerCase());
  return index === -1 ? null : index;
};

const readReadmeCounts = (failures: string[]): Partial<Record<CountName, number>> => {
  const sentence = readFileSync(README, "utf8")
    .split("\n")
    .find((line) => line.startsWith("The collection contains"));
  if (sentence === undefined) {
    failures.push('README.md has no line that starts with "The collection contains".');
    return {};
  }
  const counts: Partial<Record<CountName, number>> = {};
  for (const name of COUNT_NAMES) {
    const word = README_COUNTS[name].exec(sentence)?.[1];
    const count = word === undefined ? null : parseCount(word);
    if (count === null) {
      failures.push(`README.md count sentence has no number for "${name}" (pattern ${README_COUNTS[name]}).`);
    } else {
      counts[name] = count;
    }
  }
  return counts;
};

export const syncCatalog = async (mode: "write" | "check"): Promise<string[]> => {
  const failures: string[] = [];
  const skills = readSkillNames();
  const playbooks = readPlaybookNames();
  const fresh = render(skills, playbooks);

  if (mode === "write") {
    writeFileSync(GENERATED, fresh);
  } else if (!existsSync(GENERATED)) {
    return ["src/catalog.generated.ts is missing. Run: npm run sync"];
  } else if (readFileSync(GENERATED, "utf8") !== fresh) {
    failures.push("src/catalog.generated.ts is stale: it does not match ../skills. Run: npm run sync");
  }

  const { countKinds, CRAFT_SKILLS } = await import("../src/catalog");
  for (const name of CRAFT_SKILLS) {
    if (!skills.includes(name)) {
      failures.push(`src/catalog.ts lists the craft skill "${name}", but ../skills has no such skill.`);
    }
  }

  const actual: Record<CountName, number> = { ...countKinds(skills), playbooks: playbooks.length };
  const readme = readReadmeCounts(failures);
  for (const name of COUNT_NAMES) {
    const stated = readme[name];
    if (stated !== undefined && stated !== actual[name]) {
      failures.push(`README.md states ${stated} for "${name}", but ../skills has ${actual[name]}.`);
    }
  }
  return failures;
};

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === import.meta.filename) {
  const mode = process.argv.includes("--check") ? "check" : "write";
  const failures = await syncCatalog(mode);
  if (failures.length > 0) {
    process.stderr.write(`sync-catalog (${mode}) failed:\n${failures.map((failure) => `  - ${failure}\n`).join("")}`);
    process.exit(1);
  }
  process.stdout.write(
    mode === "write" ? "Wrote src/catalog.generated.ts. Counts match README.md.\n" : "src/catalog.generated.ts is current. Counts match README.md.\n",
  );
}
